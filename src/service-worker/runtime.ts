import type { SessionConfig } from '../shared/contracts'
import { BUILD_POLICY } from '../shared/build-policy'
import { toGalleryError } from '../shared/errors'
import type { VerifiedBlockSource } from '../network/types'
import { configuredGatewayEvidence } from '../network/ipfs-source'
import { parseBlockCid, verifyBlock } from '../network/verify'
import { record, validIdentity } from '../worker/protocol'
import { BLOCK_PATH, BOUNDS, canonicalCid, domain, exact, HEADERS, noPorts, ownerIdentity, parseControl, parseOpen,
  responseHeaders, stats, VERSION, type BindingIdentity } from './protocol'
import { reject, reply } from './rpc'
import { latch } from './ownership'

export interface WindowIdentity { id: string; url: string; type: string }
export interface ServiceRuntimeDependencies {
  scope: string
  /** Fixed by the entry's real global lifetime, not generated by this factory. */
  boot: string
  clients: { get(id: string): Promise<WindowIdentity | undefined> }
  /** Business results and the optional real-cleanup snapshot barrier remain independent. */
  createSource(config: SessionConfig): VerifiedBlockSource
  now?: () => number
  token?: () => string
}
interface Consumer {
  id: number; cid: string; ticket: string; expires: number; used: boolean; delivered: boolean; cancelled: boolean
  flight?: Flight; timer?: ReturnType<typeof setTimeout>; released: boolean
  local?: ReturnType<typeof latch>; cancellation?: Promise<void>
}
interface AdmittedBlock { bytes: Uint8Array; conclusion: 'hash-verified' | 'configured-gateway'; gateway?: string }
type Outcome = ({ ok: true } & AdmittedBlock) | { ok: false; error: unknown }
interface Flight {
  cid: string; controller: AbortController; consumers: Set<Consumer>; promise: Promise<AdmittedBlock>
  settled: boolean; bytes: number
  cleanup: Promise<void>; outcome?: Outcome
  waiters: Map<Consumer, { resolve(bytes: Uint8Array): void; reject(error: unknown): void }>
}
const MAINTENANCE_WORKING_BYTES = 1024 * 1024

interface Binding extends BindingIdentity {
  clientId: string; config: SessionConfig; capability: string; source: VerifiedBlockSource
  port: MessagePort; sequence: number; lastBlock: number; consumers: Map<number, Consumer>
  flights: Map<string, Flight>; closed: boolean; touched: number; controls: number
  idle?: ReturnType<typeof setTimeout>
  drainPromise?: Promise<void>
  attempt: Attempt
  cleanupError?: unknown
  roots: string[]; contentSeen: boolean; leaseUntil: number; maintainSequence: number
  maintenance?: Promise<void>; maintenanceController?: AbortController
}
interface Attempt { number: number; binding?: Binding; done: Promise<void>; finish(): void }
interface Owner {
  clientId: string; secret: string; observed: number; fence: number; attempts: Map<number, Attempt>
  drain?: Promise<void>; status: 'draining' | 'settled' | 'unknown'
  retired: boolean
}

/** No content retrieval happens until a single-use, WindowClient-bound fetch consumes a ticket. */
export function createServiceWorkerRuntime(dependencies: ServiceRuntimeDependencies) {
  const base = new URL(dependencies.scope)
  const prefix = new URL(BLOCK_PATH, base).href
  const now = dependencies.now ?? Date.now
  const token = dependencies.token ?? (() => crypto.randomUUID())
  const epoch = dependencies.boot
  const bindings = new Map<string, Binding>()
  const owners = new Map<string, Owner>()
  let management = 0
  let pendingOpens = 0
  let collection: Promise<void> | undefined
  let flightCount = 0
  let consumerCount = 0
  let responseBytes = 0
  let workingBytes = 0
  let handlers = 0

  function inScope(client: WindowIdentity | undefined): client is WindowIdentity {
    if (!client || client.type !== 'window' || !client.id) return false
    const url = new URL(client.url)
    return url.origin === base.origin && url.pathname.startsWith(base.pathname)
  }
  function retireOwner(id: string, owner: Owner): void {
    if (owner.retired) return
    owner.retired = true
    owner.fence = Number.MAX_SAFE_INTEGER
    if (!owner.attempts.size) { owners.delete(id); return }
    owner.status = 'draining'
    owner.drain = Promise.all([...owner.attempts.values()].map(async entry => {
      if (entry.binding) { await close(entry.binding); entry.binding.port.close() }
      await entry.done
    })).then(() => {
      if (owners.get(id) === owner && !owner.attempts.size) owners.delete(id)
    }, () => { owner.status = 'unknown' })
  }
  function collectDepartedOwners(): Promise<void> {
    if (collection) return collection
    const scan = Promise.all([...owners].map(async ([id, owner]) => {
      let client: WindowIdentity | undefined
      try { client = await dependencies.clients.get(owner.clientId) } catch { return }
      if (client === undefined || (client.id === owner.clientId && !inScope(client))) retireOwner(id, owner)
    })).then(() => {})
    collection = scan
    void scan.finally(() => { if (collection === scan) collection = undefined }).catch(() => {})
    return scan
  }
  async function live(binding: Binding, clientId = binding.clientId): Promise<void> {
    if (binding.closed || clientId !== binding.clientId) throw domain('INVALID_INPUT')
    const client = await dependencies.clients.get(clientId)
    if (!inScope(client) || client.id !== clientId) { void close(binding).catch(() => {}); throw domain('NETWORK') }
  }
  function armIdle(binding: Binding): void {
    clearTimeout(binding.idle)
    if (!binding.closed) binding.idle = setTimeout(() => {
      if (!binding.consumers.size && !binding.flights.size && !binding.controls && binding.leaseUntil <= now()) idle(binding)
      else armIdle(binding)
    }, BOUNDS.idleMs)
  }
  function idle(binding: Binding): void {
    void close(binding).then(() => {
      binding.port.postMessage({ v: VERSION, type: 'idle', sessionId: binding.sessionId,
        bindingId: binding.bindingId, epoch: binding.epoch })
      binding.port.close()
    }).catch(() => {})
  }
  function release(binding: Binding, consumer: Consumer): void {
    if (consumer.released) return
    consumer.released = true
    clearTimeout(consumer.timer)
    binding.consumers.delete(consumer.id)
    consumerCount--
    responseBytes -= binding.config.limits.maxBlockBytes * 2
    armIdle(binding)
  }
  function cancel(binding: Binding, consumer: Consumer): Promise<void> {
    if (consumer.cancellation) return consumer.cancellation
    consumer.cancelled = true
    clearTimeout(consumer.timer)
    const flight = consumer.flight
    let last = false
    if (flight) {
      flight.waiters.get(consumer)?.reject(domain('CANCELLED'))
      flight.waiters.delete(consumer)
      flight.consumers.delete(consumer)
      if (!flight.settled && !flight.consumers.size) {
        last = true
        flight.controller.abort(domain('CANCELLED'))
      }
    }
    consumer.cancellation = (async () => {
      await consumer.local?.promise
      if (flight && last) await flight.cleanup
      release(binding, consumer)
    })()
    void consumer.cancellation.catch(() => {})
    return consumer.cancellation
  }
  function close(binding: Binding): Promise<void> {
    if (binding.drainPromise) return binding.drainPromise
    binding.closed = true
    clearTimeout(binding.idle)
    binding.drainPromise = (async () => {
      const consumers = [...binding.consumers.values()].map(consumer => cancel(binding, consumer))
      binding.leaseUntil = 0
      binding.maintenanceController?.abort(domain('CANCELLED'))
      binding.source.dispose()
      await binding.maintenance
      await Promise.all(consumers)
      await Promise.all([...binding.flights.values()].map(flight => flight.cleanup))
      await (binding.source.drained?.() ?? binding.source.settled?.())
      bindings.delete(binding.bindingId)
      binding.attempt.finish()
    })()
    void binding.drainPromise.catch(() => {})
    return binding.drainPromise
  }
  function expire(binding: Binding): void {
    for (const consumer of binding.consumers.values()) {
      if (consumer.expires <= now()) void cancel(binding, consumer).catch(() => {})
    }
    if (!binding.consumers.size && !binding.flights.size && binding.leaseUntil <= now() && binding.touched + BOUNDS.idleMs <= now()) idle(binding)
  }
  function armConsumer(binding: Binding, consumer: Consumer, duration: number): void {
    clearTimeout(consumer.timer)
    consumer.expires = now() + duration
    consumer.timer = setTimeout(() => { void cancel(binding, consumer).catch(() => {}) }, duration)
  }
  async function control(binding: Binding, value: Record<string, unknown>): Promise<unknown> {
    if (value.type === 'close') { await close(binding); return null }
    expire(binding)
    if (binding.closed) throw domain('NETWORK')
    if (binding.cleanupError !== undefined) throw binding.cleanupError
    binding.touched = now()
    const id = value.blockRequestId as number
    if (value.type === 'prepare-block') {
      const cid = canonicalCid(value.cid, binding.config.limits.maxBlockBytes)
      if (id <= binding.lastBlock) throw domain('INVALID_INPUT')
      binding.lastBlock = id
      // Reserve the retained admission snapshot and one exclusive private-port delivery until consume/discard.
      const bytes = binding.config.limits.maxBlockBytes * 2
      if (consumerCount >= Math.min(BOUNDS.consumers, BOUNDS.responses)
        || binding.consumers.size >= BOUNDS.perBinding
        || responseBytes + bytes > BOUNDS.responseBytes) throw domain('LIMIT')
      const consumer: Consumer = { id, cid, ticket: token(), expires: 0, used: false, delivered: false, cancelled: false, released: false }
      binding.consumers.set(id, consumer)
      consumerCount++
      responseBytes += bytes
      armConsumer(binding, consumer, BOUNDS.ticketMs)
      try {
        await live(binding)
        if (consumer.cancelled || consumer.released || binding.closed) throw domain('CANCELLED')
        binding.contentSeen = true
        return { ticket: consumer.ticket }
      } catch (error) { await cancel(binding, consumer); throw error }
    }
    await live(binding)
    if (value.type === 'snapshot') return stats(binding.source.snapshot(), binding.config)
    const consumer = binding.consumers.get(id)
    if (value.type === 'read-block') {
      if (!consumer || !consumer.used || consumer.delivered || consumer.cancelled || binding.closed) throw domain('INVALID_INPUT')
      const outcome = consumer.flight?.outcome
      if (!outcome) throw domain('INVALID_INPUT')
      if (!outcome.ok) throw outcome.error
      const bytes = outcome.bytes.slice().buffer
      consumer.delivered = true
      return { sessionId: binding.sessionId, bindingId: binding.bindingId, epoch, blockRequestId: id,
        cid: consumer.cid, byteLength: bytes.byteLength, bytes, policy: BUILD_POLICY }
    }
    if (!consumer) return null
    if (value.type === 'consume' && (!consumer.delivered || !consumer.flight?.outcome?.ok || consumer.cancelled)) throw domain('INVALID_INPUT')
    if (value.type === 'consume') {
      await consumer.local?.promise
      await consumer.flight!.cleanup
      release(binding, consumer)
    }
    else await cancel(binding, consumer)
    return null
  }
  async function open(value: unknown, source: WindowIdentity | null, port: MessagePort): Promise<void> {
    let pending: Attempt | undefined
    let owner: Owner | undefined
    let admitted = false
    let request: ReturnType<typeof parseOpen> | undefined
    try {
      request = parseOpen(value)
      if (!inScope(source ?? undefined) || request.boot !== epoch) throw domain('INVALID_INPUT')
      owner = ownership(request.ownerId, request.secret, source!.id)
      if (request.attempt <= owner.observed) throw domain('CANCELLED')
      owner.observed = Math.max(owner.observed, request.attempt)
      if (request.attempt <= owner.fence || owner.attempts.has(request.attempt)) throw domain('CANCELLED')
      if (pendingOpens + bindings.size >= BOUNDS.bindings) throw domain('LIMIT')
      let finish!: () => void
      const done = new Promise<void>(resolve => { finish = resolve })
      const holder = owner
      const number = request.attempt
      pending = { number, done, finish: () => { holder.attempts.delete(number); finish() } }
      owner.attempts.set(request.attempt, pending)
      pendingOpens++
      admitted = true
      const client = await dependencies.clients.get(source!.id)
      if (!inScope(client) || client.id !== source!.id || client.url !== source!.url) throw domain('INVALID_INPUT')
      if (owner.retired || owners.get(request.ownerId) !== owner || request.attempt <= owner.fence) throw domain('CANCELLED')
      for (const binding of bindings.values()) expire(binding)
      if (bindings.size >= BOUNDS.bindings) throw domain('LIMIT')
      const config: SessionConfig = { gateways: [...request.config.gateways], limits: { ...request.config.limits,
        maxBlockCacheBytes: Math.min(request.config.limits.maxBlockCacheBytes, BOUNDS.cachePerBinding),
        maxBlockConcurrency: Math.min(request.config.limits.maxBlockConcurrency, BOUNDS.flights) } }
      const binding: Binding = { sessionId: request.sessionId, bindingId: token(), epoch,
        clientId: client.id, config, capability: token(), source: dependencies.createSource(config), port,
        sequence: 0, lastBlock: 0, consumers: new Map(), flights: new Map(), closed: false, touched: now(), controls: 0,
        attempt: pending, roots: request.roots, contentSeen: false,
        leaseUntil: request.roots.length ? now() + BOUNDS.leaseMs : 0, maintainSequence: 0 }
      pending.binding = binding
      bindings.set(binding.bindingId, binding)
      if (owner.retired || owners.get(request.ownerId) !== owner || request.attempt <= owner.fence) { await close(binding); throw domain('CANCELLED') }
      port.onmessage = event => {
        let sequence = record(event.data) && Number.isSafeInteger(event.data.sequence) ? event.data.sequence as number : 0
        try {
          noPorts(event)
          const command = parseControl(event.data, binding, binding.sequence)
          sequence = command.sequence as number
          binding.sequence = sequence
          if (binding.controls >= BOUNDS.controls) throw domain('LIMIT')
          binding.controls++
          void control(binding, command).then(result => {
            reply(port, sequence, result, command.type === 'read-block' ? [(result as { bytes: ArrayBuffer }).bytes] : [])
            if (command.type === 'close') port.close()
          }, error => reject(port, sequence, error)).finally(() => { binding.controls-- })
        } catch (error) {
          reject(port, sequence, error)
          void close(binding).catch(() => {})
        }
      }
      port.onmessageerror = () => { void close(binding).catch(() => {}) }
      port.start()
      armIdle(binding)
      reply(port, 0, { v: VERSION, sessionId: binding.sessionId, bindingId: binding.bindingId,
        epoch, capability: binding.capability, maxBlockBytes: config.limits.maxBlockBytes, policy: BUILD_POLICY })
    } catch (error) {
      if (pending && !pending.binding) pending.finish()
      if (request && !owners.get(request.ownerId)?.attempts.has(request.attempt)
        && (!pending?.binding || !bindings.has(pending.binding.bindingId))) {
        const { code, message, retryable } = toGalleryError(error)
        port.postMessage({ v: VERSION, sequence: 0, ok: false, error: { code, message: message.slice(0, 512), retryable },
          admission: { boot: epoch, ownerId: request.ownerId, attempt: request.attempt, state: 'settled' } })
      } else reject(port, 0, error)
      port.close()
    } finally { if (admitted) pendingOpens-- }
  }
  function ownership(id: string, secret: string, clientId: string): Owner {
    let owner = owners.get(id)
    if (owner && (owner.clientId !== clientId || owner.secret !== secret)) throw domain('INVALID_INPUT')
    if (owner?.retired) throw domain('CANCELLED')
    if (!owner) {
      if (owners.size >= BOUNDS.owners) throw domain('LIMIT')
      owner = { clientId, secret, observed: 0, fence: 0, attempts: new Map(), status: 'unknown', retired: false }
      owners.set(id, owner)
    }
    return owner
  }
  async function manage(value: unknown, source: WindowIdentity | null, port: MessagePort): Promise<void> {
    let admitted = false
    try {
      if (!inScope(source ?? undefined) || !record(value) || value.v !== VERSION) throw domain('INVALID_INPUT')
      if (management >= BOUNDS.management) throw domain('LIMIT')
      management++; admitted = true
      if (value.type === 'maintain') {
        exact(value, ['v', 'type', 'sessionId', 'bindingId', 'epoch', 'capability', 'sequence'])
        const binding = bindings.get(value.bindingId as string)
        const actual = await dependencies.clients.get(source!.id)
        if (!inScope(actual) || actual.id !== source!.id || actual.url !== source!.url || !binding ||
          binding.clientId !== actual.id || binding.closed || value.sessionId !== binding.sessionId ||
          value.epoch !== binding.epoch || value.capability !== binding.capability ||
          !Number.isSafeInteger(value.sequence) || (value.sequence as number) <= binding.maintainSequence) throw domain('INVALID_INPUT')
        binding.maintainSequence = value.sequence as number
        if (!binding.roots.length && !binding.contentSeen) throw domain('INVALID_INPUT')
        binding.leaseUntil = now() + BOUNDS.leaseMs
        armIdle(binding)
        if (!binding.maintenance && !binding.flights.size
          && workingBytes + MAINTENANCE_WORKING_BYTES <= BOUNDS.workingBytes) {
          const controller = new AbortController()
          binding.maintenanceController = controller
          workingBytes += MAINTENANCE_WORKING_BYTES
          const timer = setTimeout(() => controller.abort(domain('TIMEOUT')), BOUNDS.maintainMs)
          const task = Promise.resolve().then(() => binding.source.maintain?.(binding.roots, controller.signal)).finally(() => clearTimeout(timer))
          binding.maintenance = task
          void task.then(() => {
            workingBytes -= MAINTENANCE_WORKING_BYTES
            if (binding.maintenance === task) binding.maintenance = undefined
            if (binding.maintenanceController === controller) binding.maintenanceController = undefined
          }, error => { binding.cleanupError = error ?? domain('NETWORK') })
        }
        await binding.maintenance
        reply(port, 0, { sessionId: binding.sessionId, bindingId: binding.bindingId, epoch, sequence: value.sequence })
        return
      }
      let owner: Owner | undefined
      let attempt = 0
      if (value.type === 'reconcile') {
        exact(value, ['v', 'type', 'ownerId', 'attempt', 'secret', 'boot'])
        const identity = ownerIdentity(value)
        if (!validIdentity(value.boot)) throw domain('INVALID_INPUT')
        owner = ownership(identity.ownerId, identity.secret, source!.id)
        attempt = identity.attempt
        // Fence synchronously, before clients.get or pending open validation can resume.
        if (attempt > owner.fence) {
          owner.fence = attempt
          owner.status = 'draining'
          const entries = [...owner.attempts.values()].filter(entry => entry.number <= attempt)
          const owned = owner
          const fence = attempt
          owner.drain = Promise.all(entries.map(async entry => {
            if (entry.binding) { await close(entry.binding); entry.binding.port.close() }
            await entry.done
          })).then(() => { if (owned.fence === fence) owned.status = 'settled' },
            () => { if (owned.fence === fence) owned.status = 'unknown' })
        }
      } else { exact(value, ['v', 'type']); if (value.type !== 'identify') throw domain('INVALID_INPUT') }
      const actual = await dependencies.clients.get(source!.id)
      if (!inScope(actual) || actual.id !== source!.id || actual.url !== source!.url) throw domain('INVALID_INPUT')
      if (!owner) { await collectDepartedOwners(); reply(port, 0, { boot: epoch, policy: BUILD_POLICY }) }
      else {
        const pending = [...owner.attempts.values()].some(entry => entry.number <= attempt)
        reply(port, 0, { boot: epoch, ownerId: value.ownerId, attempt,
          state: value.boot !== epoch || owner.observed < attempt ? 'unknown'
            : !pending ? 'settled' : owner.status === 'unknown' ? 'unknown' : 'draining' })
      }
    } catch (error) { reject(port, 0, error) }
    finally { if (admitted) management--; port.close() }
  }
  function start(binding: Binding, consumer: Consumer): Flight {
    const existing = binding.flights.get(consumer.cid)
    if (existing) {
      if (existing.controller.signal.aborted) throw domain('CANCELLED')
      existing.consumers.add(consumer)
      return existing
    }
    // Two attempts (each owned result + reader growth), one admission snapshot, and bounded routing buffers.
    // The network attempt budget is a sublimit on these same allocations, not an additional allowance.
    const bytes = binding.config.limits.maxBlockBytes * 5 + 512 * 1024
    if (flightCount >= BOUNDS.flights || binding.flights.size >= binding.config.limits.maxBlockConcurrency
      || workingBytes + bytes > BOUNDS.workingBytes) throw domain('LIMIT')
    const controller = new AbortController()
    const flight: Flight = { cid: consumer.cid, controller, consumers: new Set([consumer]), waiters: new Map(),
      promise: Promise.resolve({ bytes: new Uint8Array(), conclusion: 'hash-verified' }), cleanup: Promise.resolve(), settled: false, bytes }
    flightCount++
    workingBytes += bytes
    binding.flights.set(consumer.cid, flight)
    const timer = setTimeout(() => controller.abort(domain('TIMEOUT')), binding.config.limits.blockTimeoutMs)
    flight.promise = (async () => {
      try {
        const result = await binding.source.get(consumer.cid, controller.signal)
        controller.signal.throwIfAborted()
        if (!(result instanceof Uint8Array)) throw domain('INTEGRITY')
        const max = binding.config.limits.maxBlockBytes
        const cid = parseBlockCid(consumer.cid, max)
        if (result.byteLength > max) throw domain('LIMIT')
        const evidence = configuredGatewayEvidence(binding.source, consumer.cid, result)
        // Capture before any asynchronous digest: the producer cannot mutate admitted or delivered bytes.
        const snapshot = new Uint8Array(result.byteLength)
        snapshot.set(result)
        if (BUILD_POLICY.trustless || !evidence) await verifyBlock(cid, snapshot, max)
        controller.signal.throwIfAborted()
        return { bytes: snapshot, conclusion: evidence && !BUILD_POLICY.trustless ? 'configured-gateway' : 'hash-verified',
          ...(evidence && !BUILD_POLICY.trustless ? { gateway: evidence.gateway } : {}) } satisfies AdmittedBlock
      } finally {
        clearTimeout(timer)
      }
    })()
    const outcome = (value: Outcome) => {
      flight.outcome = value
      for (const waiter of flight.waiters.values()) {
        if (value.ok) waiter.resolve(value.bytes)
        else waiter.reject(value.error)
      }
      flight.waiters.clear()
    }
    void flight.promise.then(block => outcome({ ok: true, ...block }), error => outcome({ ok: false, error }))
    flight.cleanup = flight.promise.then(() => {}, () => {}).then(() => binding.source.settled?.()).then(() => {
      flight.settled = true
      flightCount--
      workingBytes -= bytes
      binding.flights.delete(consumer.cid)
    }, error => { binding.cleanupError = error ?? domain('NETWORK'); throw binding.cleanupError })
    void flight.cleanup.catch(() => {})
    return flight
  }
  function waitForBlock(flight: Flight, consumer: Consumer): Promise<Uint8Array> {
    if (consumer.cancelled) return Promise.reject(domain('CANCELLED'))
    if (flight.outcome) return flight.outcome.ok ? Promise.resolve(flight.outcome.bytes) : Promise.reject(flight.outcome.error)
    return new Promise((resolve, reject) => { flight.waiters.set(consumer, { resolve, reject }) })
  }
  async function fetchBlock(request: Request, clientId: string): Promise<Response> {
    let binding: Binding | undefined
    let consumer: Consumer | undefined
    let removeAbort = () => {}
    let id = 0
    let admitted = false
    const started = now()
    try {
      const url = new URL(request.url)
      const cid = request.url.slice(prefix.length)
      if (request.method !== 'GET' || request.body !== null || request.mode === 'navigate'
        || request.headers.has('range') || url.search || url.hash || !cid || cid.includes('/') || cid.includes('%')) throw domain('INVALID_INPUT')
      binding = bindings.get(request.headers.get(HEADERS.bindingId) ?? '')
      if (!binding || request.headers.get(HEADERS.epoch) !== epoch) throw domain('NETWORK')
      if (request.headers.get(HEADERS.version) !== String(VERSION)
        || request.headers.get(HEADERS.capability) !== binding.capability) throw domain('INVALID_INPUT')
      await live(binding, clientId)
      expire(binding)
      if (binding.closed) throw domain('NETWORK')
      canonicalCid(cid, binding.config.limits.maxBlockBytes)
      const rawId = request.headers.get(HEADERS.blockRequestId) ?? ''
      if (!/^[1-9]\d{0,15}$/.test(rawId)) throw domain('INVALID_INPUT')
      id = Number(rawId)
      consumer = binding.consumers.get(id)
      if (!consumer || consumer.cancelled || consumer.used || consumer.expires <= now()
        || consumer.cid !== cid || request.headers.get(HEADERS.ticket) !== consumer.ticket) throw domain('INVALID_INPUT')
      consumer.used = true
      consumer.local = latch()
      handlers++
      admitted = true
      armConsumer(binding, consumer, binding.config.limits.blockTimeoutMs + BOUNDS.bodyMs)
      const owner = binding
      const target = consumer
      const abort = () => { void cancel(owner, target).catch(() => {}) }
      request.signal.addEventListener('abort', abort, { once: true })
      removeAbort = () => request.signal.removeEventListener('abort', abort)
      if (request.signal.aborted) throw domain('CANCELLED')
      consumer.flight = start(binding, consumer)
      await waitForBlock(consumer.flight, consumer)
      if (consumer.cancelled || binding.closed) throw domain('CANCELLED')
      armConsumer(binding, consumer, BOUNDS.bodyMs)
      const headers = responseHeaders(binding, id)
      return new Response(null, { status: 204, headers })
    } catch (error) {
      if (binding && consumer && admitted) void cancel(binding, consumer).catch(() => {})
      const raw = toGalleryError(error)
      const detail = { code: raw.code, message: raw.message.slice(0, 512), retryable: raw.retryable }
      const status = detail.code === 'LIMIT' ? 429 : detail.code === 'TIMEOUT' ? 504
        : detail.code === 'CANCELLED' ? 410 : detail.code === 'INVALID_INPUT' || detail.code === 'UNSUPPORTED' ? 400 : 502
      if (admitted && consumer) {
        console.info('[ipfs-gallery:network]', { event: detail.code === 'CANCELLED' ? 'sw-read-cancelled' : 'sw-read-failure',
          cid: consumer.cid, code: detail.code, status, elapsedMs: now() - started })
      }
      const headers = responseHeaders(binding ?? { sessionId: '', bindingId: '', epoch }, id)
      headers.set('Content-Type', 'application/json')
      return new Response(JSON.stringify(detail), { status: !binding && detail.code === 'NETWORK' ? 409 : status, headers })
    } finally {
      removeAbort()
      if (admitted) { handlers--; consumer!.local!.resolve() }
    }
  }
  return {
    epoch, open, manage,
    handleFetch(request: Request, clientId: string): Promise<Response> | undefined {
      return request.url.startsWith(prefix) ? fetchBlock(request, clientId) : undefined
    },
    async dispose(): Promise<void> {
      await Promise.all([...bindings.values()].map(async binding => { await close(binding); binding.port.close() }))
    },
    usage() { return { bindings: bindings.size, flights: flightCount, consumers: consumerCount, responseBytes, workingBytes,
      owners: owners.size, handlers, waiters: [...bindings.values()].reduce((total, binding) => total
        + [...binding.flights.values()].reduce((sum, flight) => sum + flight.waiters.size, 0), 0) } },
    acceptsOpen(value: unknown): boolean { return record(value) && ['open', 'identify', 'reconcile', 'maintain'].includes(value.type as string) },
  }
}

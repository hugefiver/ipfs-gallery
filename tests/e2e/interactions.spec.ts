test('a failed original retains its index; a valid thumbnail is not reader readiness, and retry recovers', async ({ page, previewFixtures, network }) => {
  const [first, failed, third] = previewFixtures.items
  for (const gateway of [network.slow, network.fast]) gateway.setBlockMode(failed!.original.cid, { kind: '404' })
  await page.goto(sourceUrl('meta', previewFixtures.manifest.ref))
  await expectReaderImage(page, first!.original.bytes)
  await enterAlbum(page)
  await expectImageBytes(ui.tileImage(page, failed!.title), failed!.thumbnail.bytes)
  await selectAlbumItem(page, failed!.title)
  await expect(ui.readerSurface(page).getByRole('alert').first()).toBeVisible()
  await expect(ui.reader(page).getByRole('img')).toHaveCount(0)
  expect(new URL(page.url()).searchParams.get('item')).toBe(failed!.id)
  for (const gateway of [network.slow, network.fast]) gateway.setBlockMode(failed!.original.cid, undefined)
  await ui.readerSurface(page).getByRole('button', { name: '重试加载', exact: true }).click()
  await expectReaderImage(page, failed!.original.bytes)
  await openReaderTools(page)
  await ui.next(page).click()
  await expectReaderImage(page, third!.original.bytes)
})

for (const mode of ['corrupt', '404', '429'] as const) {
  test(`${mode} gateway falls back; multiblock download retains exact verified bytes`, async ({ page, galleryFixtures, network }) => {
    network.slow.setMode({ kind: mode })
    await page.goto(sourceUrl('cid', galleryFixtures.multiblock.ref))
    await expectReaderImage(page, galleryFixtures.multiblock.bytes)
    const status = mode === 'corrupt' ? 200 : Number(mode)
    expect(network.slow.requests.some(record => record.status === status)).toBe(true)
    const rejectedCid = network.slow.requests.find(record => record.status === status)!.cid
    expect(network.fast.requests.some(record => record.cid === rejectedCid && record.status === 200)).toBe(true)
    await openReaderTools(page)
    await expectDownloadBytes(page, ui.readerTools(page), galleryFixtures.multiblock.bytes)
  })
}

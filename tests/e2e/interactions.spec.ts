test('album selection and local sorting preserve replace history and resident original bytes', async ({ page, galleryFixtures, network }) => {
  await page.goto(sourceUrl('unixfs', galleryFixtures.directories.json.ref))
  await expectReaderImage(page, galleryFixtures.raw.bytes)
  const historyLength = await page.evaluate(() => history.length)
  await selectAlbumItem(page, '蓝色影像')
  await expectReaderImage(page, galleryFixtures.dagPb.bytes)
  const selected = new URL(page.url()).searchParams.get('item')
  expect(selected).toBeTruthy()
  await openPanel(page, 'filters')
  await ui.sort(page).selectOption('name')
  await page.keyboard.press('Escape')
  await expectReaderImage(page, galleryFixtures.dagPb.bytes)
  expect(new URL(page.url()).searchParams.get('item')).toBe(selected)
  const url = page.url()
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await openMenu(page)
  await ui.dialog(page).getByRole('button', { name: '复制分享链接', exact: true }).click()
  await expect(ui.dialog(page).getByRole('status')).toBeVisible()
  const shared = new URL(await page.evaluate(() => navigator.clipboard.readText()))
  expect(shared.searchParams.get('item')).toBe(selected)
  expect([...shared.searchParams.keys()].some(key => ['mode', 'chrome', 'panel', 'overlay'].includes(key))).toBe(false)
  expect(page.url()).toBe(url)
  await page.keyboard.press('Escape')
  const originalCid = galleryFixtures.directories.json.files['media/nested/无扩展名']!.cid
  const reads = () => network.bridge.routes.filter(route => new URL(route.url).pathname.endsWith(`/${originalCid}`)).length
  const initial = reads()
  await openPanel(page, 'info')
  const dialog = ui.dialog(page)
  await expect(dialog).toHaveAttribute('aria-modal', 'true')
  await expect(dialog.getByText(galleryFixtures.directories.json.ref.cid, { exact: true })).toBeVisible()
  for (let tab = 0; tab < 8; tab += 1) {
    await page.keyboard.press('Tab')
    expect(await dialog.evaluate(element => element.contains(document.activeElement))).toBe(true)
  }
  await page.keyboard.press('Escape')
  await expect(ui.menuButton(page)).toBeFocused()
  await openReaderTools(page)
  await expectDownloadBytes(page, ui.readerTools(page), galleryFixtures.dagPb.bytes)
  expect(reads()).toBe(initial)
  expect(page.url()).toBe(url)
  expect(await page.evaluate(() => history.length)).toBe(historyLength)
  await page.goto(url)
  await expectReaderImage(page, galleryFixtures.dagPb.bytes)
  await expect(ui.menuButton(page)).toBeVisible()
})

